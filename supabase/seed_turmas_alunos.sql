-- ─── 4. VERIFICAÇÃO ──────────────────────────────────────────────────────────
SELECT t.nome AS turma, COUNT(a.id) AS total_alunos
FROM turmas t
LEFT JOIN alunos a ON a.turma_id = t.id AND a.ativo = TRUE
WHERE t.ativa = TRUE
GROUP BY t.nome
ORDER BY t.nome;
